export type Maybe<T> = T | null;
export type InputMaybe<T> = Maybe<T>;
/** All built-in and custom scalars, mapped to their actual values */
export type Scalars = {
  ID: { input: string; output: string; }
  String: { input: string; output: string; }
  Boolean: { input: boolean; output: boolean; }
  Int: { input: number; output: number; }
  Float: { input: number; output: number; }
  DateTime: { input: string; output: string; }
};

export type Author = {
  __typename?: 'Author';
  comments: Array<Comment>;
  email: Scalars['String']['output'];
  id: Scalars['ID']['output'];
  name: Scalars['String']['output'];
};

export type Choice = {
  __typename?: 'Choice';
  choiceText: Scalars['String']['output'];
  createdAt: Scalars['DateTime']['output'];
  id: Scalars['ID']['output'];
  poll: Poll;
  updatedAt: Scalars['DateTime']['output'];
  votes: Scalars['Int']['output'];
};

export type ChoiceFilter = {
  pollId?: InputMaybe<Scalars['ID']['input']>;
};

export type Comment = {
  __typename?: 'Comment';
  author?: Maybe<Author>;
  authorName: Scalars['String']['output'];
  content: Scalars['String']['output'];
  createdAt: Scalars['DateTime']['output'];
  id: Scalars['ID']['output'];
  likes: Scalars['Int']['output'];
  poll: Poll;
  viewerLiked: Scalars['Boolean']['output'];
};

export type Mutation = {
  __typename?: 'Mutation';
  createAuthor: Author;
  createChoice: Choice;
  createComment: Comment;
  createPoll: Poll;
  login: User;
  logout: Scalars['Boolean']['output'];
  toggleCommentLike: Comment;
  vote: Poll;
};


export type MutationCreateAuthorArgs = {
  email: Scalars['String']['input'];
  name: Scalars['String']['input'];
};


export type MutationCreateChoiceArgs = {
  choiceText: Scalars['String']['input'];
  pollId: Scalars['ID']['input'];
};


export type MutationCreateCommentArgs = {
  authorName?: InputMaybe<Scalars['String']['input']>;
  content: Scalars['String']['input'];
  pollId: Scalars['ID']['input'];
};


export type MutationCreatePollArgs = {
  authorId: Scalars['ID']['input'];
  choices?: InputMaybe<Array<Scalars['String']['input']>>;
  pubDate: Scalars['DateTime']['input'];
  question: Scalars['String']['input'];
};


export type MutationLoginArgs = {
  password: Scalars['String']['input'];
  username: Scalars['String']['input'];
};


export type MutationToggleCommentLikeArgs = {
  commentId: Scalars['ID']['input'];
};


export type MutationVoteArgs = {
  choiceId: Scalars['ID']['input'];
  pollId: Scalars['ID']['input'];
};

export type Poll = {
  __typename?: 'Poll';
  author: Author;
  choices: Array<Choice>;
  closesAt?: Maybe<Scalars['DateTime']['output']>;
  comments: Array<Comment>;
  createdAt: Scalars['DateTime']['output'];
  id: Scalars['ID']['output'];
  isActive: Scalars['Boolean']['output'];
  isAutoGenerated: Scalars['Boolean']['output'];
  question: Scalars['String']['output'];
  topComments: Array<Comment>;
  totalVotes: Scalars['Int']['output'];
  updatedAt: Scalars['DateTime']['output'];
  viewerChoiceId?: Maybe<Scalars['ID']['output']>;
};

export type PollConnection = {
  __typename?: 'PollConnection';
  limit: Scalars['Int']['output'];
  nodes: Array<Poll>;
  page: Scalars['Int']['output'];
  total: Scalars['Int']['output'];
};

export type PollFilter = {
  isActive?: InputMaybe<Scalars['Boolean']['input']>;
  question?: InputMaybe<Scalars['String']['input']>;
};

export type Query = {
  __typename?: 'Query';
  author?: Maybe<Author>;
  choice?: Maybe<Choice>;
  choices: Array<Choice>;
  me?: Maybe<User>;
  poll?: Maybe<Poll>;
  polls: PollConnection;
};


export type QueryAuthorArgs = {
  id: Scalars['ID']['input'];
};


export type QueryChoiceArgs = {
  id: Scalars['ID']['input'];
};


export type QueryChoicesArgs = {
  filter?: InputMaybe<ChoiceFilter>;
};


export type QueryPollArgs = {
  id: Scalars['ID']['input'];
};


export type QueryPollsArgs = {
  filter?: InputMaybe<PollFilter>;
  limit?: InputMaybe<Scalars['Int']['input']>;
  page?: InputMaybe<Scalars['Int']['input']>;
};

export type User = {
  __typename?: 'User';
  author?: Maybe<Author>;
  email: Scalars['String']['output'];
  id: Scalars['ID']['output'];
  username: Scalars['String']['output'];
};
